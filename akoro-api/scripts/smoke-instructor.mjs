#!/usr/bin/env node
/**
 * Smoke test for the instructor API.
 * Usage:
 *   EMAIL=teacher@example.com PASSWORD=secret node scripts/smoke-instructor.mjs
 *   API_URL=https://api.akoro.app EMAIL=... PASSWORD=... node scripts/smoke-instructor.mjs
 */

const BASE = process.env.API_URL || 'http://localhost:8080';
const EMAIL = process.env.EMAIL;
const PASSWORD = process.env.PASSWORD;

if (!EMAIL || !PASSWORD) {
  console.error('ERROR: Set EMAIL and PASSWORD env vars before running.');
  process.exit(1);
}

/* ── helpers ──────────────────────────────────────────────────────────── */
let cookie = '';
let pass = 0, fail = 0;

async function req(method, path, body) {
  const opts = {
    method,
    headers: { 'Content-Type': 'application/json', ...(cookie ? { Cookie: cookie } : {}) },
    credentials: 'include',
  };
  if (body) opts.body = JSON.stringify(body);
  const res = await fetch(`${BASE}${path}`, opts);

  // capture Set-Cookie from login
  const sc = res.headers.get('set-cookie');
  if (sc) cookie = sc.split(';')[0];

  let data;
  try { data = await res.json(); } catch { data = null; }
  return { ok: res.ok, status: res.status, data };
}

function check(label, condition, detail = '') {
  if (condition) {
    console.log(`  ✓  ${label}`);
    pass++;
  } else {
    console.error(`  ✗  ${label}${detail ? ' — ' + detail : ''}`);
    fail++;
  }
}

/* ── test registry ────────────────────────────────────────────────────── */
const cleanup = { courseId: null, sessionId: null, battleId: null, studentId: null };

async function testAuth() {
  console.log('\n[Auth]');
  const r = await req('POST', '/api/auth/login', { email: EMAIL, password: PASSWORD });
  check('POST /api/auth/login → 200', r.ok, `status=${r.status}`);
  check('user in response', !!r.data?.user);
  const role = r.data?.user?.role;
  check(`role is instructor or admin (got "${role}")`, role === 'instructor' || role === 'admin');
  return r.ok;
}

async function testStats() {
  console.log('\n[Stats]');
  const r = await req('GET', '/api/instructor/stats');
  check('GET /api/instructor/stats → 200', r.ok, `status=${r.status}`);
  if (r.data?.stats) {
    const s = r.data.stats;
    check('stats has total_students', 'total_students' in s);
    check('stats has active_courses', 'active_courses' in s);
    check('stats has agent_xp', 'agent_xp' in s);
  }
}

async function testProfile() {
  console.log('\n[Profile]');
  const r = await req('GET', '/api/instructor/profile');
  check('GET /api/instructor/profile → 200', r.ok, `status=${r.status}`);
  if (r.ok) {
    check('profile has email', !!r.data?.user?.email);
    const patch = await req('PATCH', '/api/instructor/profile', { bio: 'Smoke test bio' });
    check('PATCH /api/instructor/profile → 200', patch.ok, `status=${patch.status}`);
  }
}

async function testCourses() {
  console.log('\n[Courses]');
  const list = await req('GET', '/api/instructor/courses');
  check('GET /api/instructor/courses → 200', list.ok, `status=${list.status}`);

  const create = await req('POST', '/api/instructor/courses', {
    title: 'Smoke Test Course',
    description: 'Auto-generated by smoke test',
    type: 'on-demand',
    level: 'beginner',
    status: 'draft',
  });
  check('POST /api/instructor/courses → 201', create.status === 201, `status=${create.status}`);
  if (create.data?.course?.id) {
    cleanup.courseId = create.data.course.id;
    check('course has id', !!cleanup.courseId);
    check('course has slug', !!create.data.course.slug);

    const upd = await req('PATCH', `/api/instructor/courses/${cleanup.courseId}`, { title: 'Smoke Test Course (updated)' });
    check('PATCH /api/instructor/courses/:id → 200', upd.ok, `status=${upd.status}`);
  }
}

async function testSessions() {
  if (!cleanup.courseId) { console.log('\n[Sessions] skipped — no course'); return; }
  console.log('\n[Sessions]');
  const start = new Date(Date.now() + 86400000).toISOString();
  const create = await req('POST', '/api/instructor/sessions', {
    courseId: cleanup.courseId,
    title: 'Smoke Session',
    startTime: start,
    duration: 60,
    meetingLink: 'https://zoom.us/j/smoke',
  });
  check('POST /api/instructor/sessions → 201', create.status === 201, `status=${create.status}`);
  if (create.data?.session?.id) {
    cleanup.sessionId = create.data.session.id;
    const upd = await req('PATCH', `/api/instructor/sessions/${cleanup.sessionId}`, { title: 'Smoke Session Updated' });
    check('PATCH /api/instructor/sessions/:id → 200', upd.ok, `status=${upd.status}`);
  }
}

async function testStudents() {
  if (!cleanup.courseId) { console.log('\n[Students] skipped — no course'); return; }
  console.log('\n[Students]');
  const list = await req('GET', `/api/instructor/students?courseId=${cleanup.courseId}`);
  check('GET /api/instructor/students → 200', list.ok, `status=${list.status}`);

  const email = `smoke_${Date.now()}@test.akoro.dev`;
  const enrol = await req('POST', '/api/instructor/students/enrol', {
    email,
    courseId: cleanup.courseId,
    fullName: 'Smoke Student',
  });
  check('POST /api/instructor/students/enrol → 2xx', enrol.ok || enrol.status === 201, `status=${enrol.status}`);
}

async function testBattles() {
  if (!cleanup.courseId) { console.log('\n[Battles] skipped — no course'); return; }
  console.log('\n[Battles]');
  const list = await req('GET', '/api/instructor/battles');
  check('GET /api/instructor/battles → 200', list.ok, `status=${list.status}`);

  const create = await req('POST', '/api/instructor/battles', {
    topic: 'Smoke Battle',
    difficulty: 'beginner',
    battle_type: 'open',
    total_questions: 5,
    time_limit_seconds: 300,
    courseId: cleanup.courseId,
  });
  check('POST /api/instructor/battles → 201', create.status === 201, `status=${create.status}`);
  if (create.data?.battle?.id) {
    cleanup.battleId = create.data.battle.id;
    check('battle has id', !!cleanup.battleId);
    check('battle has expires_at', !!create.data.battle.expires_at);
  }
}

async function testStreaming() {
  console.log('\n[Streaming]');
  const list = await req('GET', '/api/instructor/streaming');
  check('GET /api/instructor/streaming → 200', list.ok, `status=${list.status}`);

  // connect zoom (will fail gracefully if platform rejects token — just check API layer)
  const connect = await req('POST', '/api/instructor/streaming/zoom/connect', { token: 'smoke_token_test' });
  check('POST /api/instructor/streaming/zoom/connect → 2xx or 400', connect.ok || connect.status === 400, `status=${connect.status}`);

  if (connect.ok) {
    const disconnect = await req('DELETE', '/api/instructor/streaming/zoom');
    check('DELETE /api/instructor/streaming/zoom → 200', disconnect.ok, `status=${disconnect.status}`);
  }
}

async function testTasks() {
  console.log('\n[Tasks]');
  const list = await req('GET', '/api/tasks');
  check('GET /api/tasks → 200', list.ok, `status=${list.status}`);

  const create = await req('POST', '/api/tasks', { title: 'Smoke task', task_type: 'general', priority: 'low' });
  check('POST /api/tasks → 201', create.status === 201 || create.ok, `status=${create.status}`);
  if (create.data?.task?.id) {
    const toggle = await req('PATCH', `/api/tasks/${create.data.task.id}/toggle`, {});
    check('PATCH /api/tasks/:id/toggle → 200', toggle.ok, `status=${toggle.status}`);
  }
}

async function testCleanup() {
  console.log('\n[Cleanup]');
  if (cleanup.sessionId) {
    const r = await req('DELETE', `/api/instructor/sessions/${cleanup.sessionId}`);
    check(`DELETE session ${cleanup.sessionId}`, r.ok || r.status === 404, `status=${r.status}`);
  }
  if (cleanup.courseId) {
    const r = await req('DELETE', `/api/instructor/courses/${cleanup.courseId}`);
    check(`DELETE course ${cleanup.courseId}`, r.ok || r.status === 404, `status=${r.status}`);
  }
}

/* ── runner ───────────────────────────────────────────────────────────── */
async function main() {
  console.log(`\nAkoro Instructor Smoke Test`);
  console.log(`Target: ${BASE}`);
  console.log(`Email:  ${EMAIL}`);
  console.log('─'.repeat(40));

  const authed = await testAuth();
  if (!authed) {
    console.error('\nAuth failed — cannot continue.\n');
    process.exit(1);
  }

  await testStats();
  await testProfile();
  await testCourses();
  await testSessions();
  await testStudents();
  await testBattles();
  await testStreaming();
  await testTasks();
  await testCleanup();

  console.log('\n' + '─'.repeat(40));
  console.log(`Results: ${pass} passed, ${fail} failed`);
  if (fail > 0) process.exit(1);
}

main().catch(err => { console.error(err); process.exit(1); });

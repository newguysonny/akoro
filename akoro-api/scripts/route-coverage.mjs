#!/usr/bin/env node
/**
 * scripts/route-coverage.mjs — compare the runtime route table with OpenAPI.
 *
 *   node scripts/route-coverage.mjs [--input <route-table.json>]
 *                                   [--openapi <openapi.yaml>]
 *                                   [--public <public-route-candidates.csv>]
 *                                   [--out <phase-2-route-coverage.md>]
 *                                   [--check]
 *
 * Without --input the app is extracted in-process (AKORO_ROUTE_EXPORT=1).
 * --check exits non-zero when an OpenAPI operation has no runtime route.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  compareRouteTables,
  parseCsv,
  parseOpenApi,
} from "../lib/routeCatalog.js";
import { loadRuntimeRouteTable } from "./route-runtime.mjs";

const REPO_ROOT = fileURLToPath(new URL("../../", import.meta.url));

function arg(name, fallback) {
  const index = process.argv.indexOf(name);
  return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}
const hasFlag = (name) => process.argv.includes(name);

const openapiPath = path.resolve(REPO_ROOT, arg("--openapi", "akoro-documentation/02-api/openapi.yaml"));
const publicPath = path.resolve(REPO_ROOT, arg("--public", "docs/audits/phase-0/public-route-candidates.csv"));
const outPath = path.resolve(REPO_ROOT, arg("--out", "docs/audits/phase-2-route-coverage.md"));
const inputPath = arg("--input", null);

let routes;
if (inputPath) {
  const table = JSON.parse(await readFile(path.resolve(REPO_ROOT, inputPath), "utf8"));
  routes = table.routes;
} else {
  ({ routes } = await loadRuntimeRouteTable());
}

const openapi = parseOpenApi(await readFile(openapiPath, "utf8"));
const publicCandidates = parseCsv(await readFile(publicPath, "utf8"));
const comparison = compareRouteTables({ runtime: routes, openapi, publicCandidates });

const cell = (value) => String(value ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const row = (values) => `| ${values.map(cell).join(" | ")} |`;

const counts = comparison.counts;
const lines = [
  "# Phase 2 Route Coverage",
  "",
  "Generated by `akoro-api/scripts/route-coverage.mjs` from the real Express",
  "router table, not from a static source scan.",
  "",
  "| Field | Value |",
  "| --- | --- |",
  `| Generated | ${comparison.generatedAt} |`,
  `| Extractor | \`AKORO_ROUTE_EXPORT=1\` import of \`akoro-api/app.js\`; recursive \`app._router.stack\` walk |`,
  "| Normalized table | `docs/audits/phase-2-route-table.json` (written by `export-routes.mjs`) |",
  `| OpenAPI | \`${path.relative(REPO_ROOT, openapiPath)}\` |`,
  `| Public candidates | \`${path.relative(REPO_ROOT, publicPath)}\` |`,
  "",
  "## Coverage counts",
  "",
  "| Metric | Count |",
  "| --- | ---: |",
  `| Runtime routes (method + full path, deduplicated) | ${counts.runtimeRoutes} |`,
  `| Runtime paths | ${counts.runtimePaths} |`,
  `| OpenAPI paths | ${counts.documentedPaths} |`,
  `| OpenAPI operations | ${counts.documentedOperations} |`,
  `| Documented operations present in runtime | ${counts.documentedInRuntime} |`,
  `| Documented operations missing from runtime | ${counts.missingDocumented} |`,
  `| Public route candidates | ${counts.publicCandidates} |`,
  `| Public candidates documented | ${counts.publicDocumented} |`,
  `| Public candidates without docs | ${counts.publicWithoutDocs} |`,
  `| Runtime routes not in OpenAPI | ${counts.undocumentedRuntime} |`,
  "",
  "## Documented operations",
  "",
  row(["Operation", "Method", "OpenAPI path", "Runtime path", "Present"]),
  row(["---", "---", "---", "---", "---"]),
  ...comparison.documented.map((operation) => row([
    operation.operationId || "(no operationId)",
    operation.method,
    operation.openApiPath,
    operation.runtimePath || "(missing)",
    operation.inRuntime ? "yes" : "**NO**",
  ])),
  "",
];

lines.push(
  "## Documented routes missing from the runtime table",
  "",
  comparison.missingDocumented.length
    ? [
        row(["Operation", "Method", "OpenAPI path"]),
        row(["---", "---", "---"]),
        ...comparison.missingDocumented.map((operation) => row([
          operation.operationId || "(no operationId)",
          operation.method,
          operation.openApiPath,
        ])),
      ].join("\n")
    : "None. Every documented operation resolves to a runtime route.",
  "",
);

lines.push(
  "## Public routes without docs",
  "",
  comparison.undocumentedPublic.length
    ? [
        row(["Method", "Path", "Module", "Notes"]),
        row(["---", "---", "---", "---"]),
        ...comparison.undocumentedPublic.map((route) => row([
          route.method,
          route.path,
          route.module || "",
          route.notes,
        ])),
      ].join("\n")
    : "None. Every public route candidate is documented.",
  "",
);

lines.push(
  "## Undocumented runtime routes by module",
  "",
  row(["Module", "Runtime routes not in OpenAPI"]),
  row(["---", "---:"]),
  ...comparison.undocumentedRuntimeByModule.map((entry) => row([entry.module, entry.count])),
  "",
  "## Method and caveats",
  "",
  "- The route table comes from the live Express app. `app.js` short-circuits",
  "  Redis, Socket.io, migrations, background workers, context preflight and",
  "  `httpServer.listen` only when `AKORO_ROUTE_EXPORT=1`; a normal boot is",
  "  unchanged.",
  "- During extraction `REDIS_URL` and the Postgres URLs point at a closed",
  "  local port, so import-time clients in individual modules cannot reach a",
  "  real Redis/Postgres. app.js itself creates no Redis clients and runs no",
  "  migrations or listener under the guard.",
  "- Rows are deduplicated by `METHOD path`; `occurrences` in the JSON records",
  "  how many declarations resolved to the same key.",
  "- OpenAPI paths are relative to the `/api` server base and are normalized to",
  "  `/api/...`; `{param}` becomes `:param` before matching.",
  "- Middleware names are the effective router-level and route-level function",
  "  names. Express loses the originating file, so `sourceModule` is inferred",
  "  from the `app.use(...)` mount prefix in `app.js` (longest prefix wins).",
  "- Public candidates are the Phase 0 `class=public` rows. Provider-signed and",
  "  key/secret-guarded routes are intentionally excluded from that set.",
  "",
);

await mkdir(path.dirname(outPath), { recursive: true });
await writeFile(outPath, `${lines.join("\n")}\n`);

console.log(`[coverage] runtime ${counts.runtimeRoutes} routes / ${counts.runtimePaths} paths`);
console.log(`[coverage] OpenAPI ${counts.documentedOperations} operations / ${counts.documentedPaths} paths`);
console.log(`[coverage] documented in runtime ${counts.documentedInRuntime}/${counts.documentedOperations}; missing ${counts.missingDocumented}`);
console.log(`[coverage] public ${counts.publicDocumented}/${counts.publicCandidates} documented; ${counts.publicWithoutDocs} without docs`);
console.log(`[coverage] report → ${path.relative(REPO_ROOT, outPath)}`);

for (const operation of comparison.missingDocumented) {
  console.error(`[coverage] MISSING ${operation.method} ${operation.openApiPath} (${operation.operationId || "no operationId"})`);
}

if (hasFlag("--check") && (counts.missingDocumented > 0 || counts.runtimeRoutes === 0)) {
  process.exitCode = 1;
}

// Import-time BullMQ/ioredis clients retry in the background; the work is done.
process.exit(process.exitCode || 0);
